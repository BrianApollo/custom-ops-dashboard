// Local run mode, step 1: writes backend/.local/wrangler.jsonc and
// backend/.local/.dev.vars with made-up values, applies every migration to the
// local D1 under backend/.wrangler/local-state, then seeds it.
// Pass --no-seed to skip the seed step.
import { randomBytes } from 'node:crypto'
import { spawnSync } from 'node:child_process'
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import {
  assertNoRemote,
  childEnv,
  localConfig,
  localDir,
  localTemplate,
  localVars,
  stateDir,
  wrangler,
} from './local-lib.mjs'

const template = readFileSync(localTemplate, 'utf8')
assertNoRemote(template, 'wrangler.local.template.jsonc')

mkdirSync(localDir, { recursive: true })
mkdirSync(stateDir, { recursive: true })
mkdirSync(fileURLToPath(new URL('../../frontend/dist/', import.meta.url)), { recursive: true })

const header = '// Generated by scripts/local-setup.mjs from wrangler.local.template.jsonc. Local only.\n'
writeFileSync(localConfig, header + template)
assertNoRemote(readFileSync(localConfig, 'utf8'), 'backend/.local/wrangler.jsonc')

// Keep the service token across re-runs so a running dev server stays valid
let serviceToken = randomBytes(32).toString('base64url')
if (existsSync(localVars)) {
  const previous = readFileSync(localVars, 'utf8').match(/^SERVICE_TOKEN="([^"]+)"$/m)
  if (previous) serviceToken = previous[1]
}

const vars = {
  ALLOWED_ORIGINS: 'http://localhost:8787,http://127.0.0.1:8787,http://localhost:5173',
  SERVICE_TOKEN: serviceToken,
  PUBLIC_FILES_URL: 'http://localhost:8787/files',
  CLOUDFLARE_ACCOUNT_ID: 'local-account-placeholder',
  R2_BUCKET_NAME: 'ops-dashboard-local',
  R2_ACCESS_KEY_ID: '',
  R2_SECRET_ACCESS_KEY: '',
  REDTRACK_API_KEY: '',
  CLOUDFLARE_IMAGES_ACCOUNT_ID: '',
  CLOUDFLARE_IMAGES_API_TOKEN: '',
  OPENAI_API_KEY: '',
  OPENAI_MODEL: '',
  ANTHROPIC_API_KEY: '',
  ANTHROPIC_MODEL: '',
  FAL_KEY: '',
  FAL_ADMIN_KEY: '',
  FAL_MIN_BALANCE_USD: '5',
  IMPORT_ENABLED: 'false',
  FACEBOOK_APP_ID: '',
  FACEBOOK_APP_SECRET: '',
  FACEBOOK_API_VERSION: 'v21.0',
  FACEBOOK_SYSTEM_USER_CONFIG_ID: '',
  TEAM_TIME_ZONE: 'Asia/Bangkok',
  STORAGE_FALLBACK_URL: '',
}
const lines = Object.entries(vars).map(([name, value]) => `${name}=${JSON.stringify(value)}`)
writeFileSync(localVars, `# Generated by scripts/local-setup.mjs. Made-up local values only.\n${lines.join('\n')}\n`)

console.log('Wrote backend/.local/wrangler.jsonc and backend/.local/.dev.vars')

wrangler(['d1', 'migrations', 'apply', 'DB'])

if (!process.argv.includes('--no-seed')) {
  const seed = spawnSync(process.execPath, [fileURLToPath(new URL('./local-seed.mjs', import.meta.url))], {
    stdio: 'inherit',
    env: childEnv(),
  })
  if (seed.status !== 0) process.exit(seed.status ?? 1)
}

console.log('Local setup done. Start it with `npm run local:dev`.')
