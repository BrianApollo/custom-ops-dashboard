export type ColumnType = 'text' | 'integer' | 'real' | 'checkbox' | 'json'

export type FieldMapping =
  // a plain value stored in one column. `d1Only` marks a field the dashboard
  // uses that has no counterpart in the Airtable base
  | { kind: 'column'; column: string; type: ColumnType; d1Only?: boolean }
  // a link that holds at most one record id, stored as a foreign key
  | { kind: 'fk'; column: string; target: string }
  // a many-to-many link stored in a junction table. `side` is 'a' for the
  // field the junction is built from and 'b' for the field it is checked against
  | {
      kind: 'junction'
      table: string
      selfColumn: string
      otherColumn: string
      positionColumn: string
      target: string
      side: 'a' | 'b'
    }
  // the other end of a foreign key: the ids of rows in `table` whose `column` is this row
  | { kind: 'inverse'; table: string; column: string }
  // files stored as rows in `attachments` with this field_name
  | { kind: 'attachment'; field: string }
  // formula, lookup, count or button: not stored
  | { kind: 'computed' }

export interface TableMapping {
  // tables are matched to a base by name; the same table has a different id in each base
  airtableName: string
  // the id in the original base, still accepted by the API as another name for the table
  airtableId: string
  d1Table: string
  fields: Record<string, FieldMapping>
}

const text = (column: string): FieldMapping => ({ kind: 'column', column, type: 'text' })
const integer = (column: string): FieldMapping => ({ kind: 'column', column, type: 'integer' })
const real = (column: string): FieldMapping => ({ kind: 'column', column, type: 'real' })
const checkbox = (column: string): FieldMapping => ({ kind: 'column', column, type: 'checkbox' })
const json = (column: string): FieldMapping => ({ kind: 'column', column, type: 'json' })
const d1Only = (column: string): FieldMapping => ({ kind: 'column', column, type: 'text', d1Only: true })
const fk = (column: string, target: string): FieldMapping => ({ kind: 'fk', column, target })
const inverse = (table: string, column: string): FieldMapping => ({ kind: 'inverse', table, column })
const attachment = (field: string): FieldMapping => ({ kind: 'attachment', field })
const computed: FieldMapping = { kind: 'computed' }

const junction = (
  table: string,
  selfColumn: string,
  otherColumn: string,
  target: string,
  side: 'a' | 'b',
): FieldMapping => ({
  kind: 'junction',
  table,
  selfColumn,
  otherColumn,
  positionColumn: `position_in_${selfColumn.replace(/_id$/, '')}`,
  target,
  side,
})

